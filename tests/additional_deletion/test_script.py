import pandas as pd
import unittest


def csv_to_list(csv_path):
    """Convert the contents of a CSV to a list which contains one list per row for easier comparison"""
    df = pd.read_csv(csv_path, dtype=str)
    csv_list = [df.columns.tolist()] + df.values.tolist()
    return csv_list


